def tflite_operators(model_bytes: bytes) -> list[str]:
    """Builtin operator names used by a TFLite flatbuffer (stdlib flatbuffer walk)."""
    import struct

    buf = memoryview(model_bytes)
    if len(buf) < 8 or bytes(buf[4:8]) != TFLITE_MAGIC:
        raise ValueError("not a TFLite flatbuffer")

    def u32(o: int) -> int:
        return struct.unpack_from("<I", buf, o)[0]

    def field(table: int, idx: int) -> int | None:
        vt = table - struct.unpack_from("<i", buf, table)[0]
        vt_size = struct.unpack_from("<H", buf, vt)[0]
        off_pos = 4 + 2 * idx
        if off_pos >= vt_size:
            return None
        off = struct.unpack_from("<H", buf, vt + off_pos)[0]
        return table + off if off else None

    root = u32(0)
    codes_f = field(root, 1)
    if codes_f is None:
        return []
    vec = codes_f + u32(codes_f)
    names: list[str] = []
    for i in range(u32(vec)):
        el = vec + 4 + 4 * i
        tbl = el + u32(el)
        dep = field(tbl, 0)
        new = field(tbl, 3)
        code = struct.unpack_from("<b", buf, dep)[0] if dep is not None else 0
        if new is not None:
            code = max(code, struct.unpack_from("<i", buf, new)[0])
        name = _BUILTIN_OPS[code] if 0 <= code < len(_BUILTIN_OPS) else f"BUILTIN_{code}"
        if name == "CUSTOM":
            cf = field(tbl, 1)
            if cf is not None:
                sp = cf + u32(cf)
                name = "CUSTOM:" + bytes(buf[sp + 4 : sp + 4 + u32(sp)]).decode("utf-8", "replace")
        if name not in names:
            names.append(name)
    return names


def op_resolver_source(model_bytes: bytes) -> tuple[str, list[str]]:
    """C++ lines registering exactly the ops the model uses; plus unsupported ops."""
    ops = tflite_operators(model_bytes)
    adds = [_TFLM_ADD[o] for o in ops if o in _TFLM_ADD]
    missing = [o for o in ops if o not in _TFLM_ADD]
    lines = [f"  static tflite::MicroMutableOpResolver<{max(1, len(adds))}> resolver;"]
    lines += [f"  resolver.{a}();" for a in adds]
    return "\n".join(lines), missing


_INFERENCE_CPP = """\
// Generated by Graphyn: run {name} with TensorFlow Lite Micro.
// Feed the same features the model was trained on (see preprocessing notes).
#include "tensorflow/lite/micro/micro_interpreter.h"
#include "tensorflow/lite/micro/micro_mutable_op_resolver.h"
#include "tensorflow/lite/schema/schema_generated.h"
#include "{header}"

namespace {{
constexpr int kArenaSize = {arena} * 1024;
alignas(16) uint8_t g_arena[kArenaSize];
tflite::MicroInterpreter* g_interpreter = nullptr;
}}

// Returns 0 on success.
int {sym}_setup() {{
  const tflite::Model* model = tflite::GetModel({sym});
  if (model->version() != TFLITE_SCHEMA_VERSION) return 1;
  // Exactly the operators this model uses: {ops}
{resolver}
  static tflite::MicroInterpreter interpreter(model, resolver, g_arena, kArenaSize);
  if (interpreter.AllocateTensors() != kTfLiteOk) return 2;
  g_interpreter = &interpreter;
  return 0;
}}

// Writes `n` float features into input 0 (quantizing when the input tensor is
// int8/uint8), runs the model and returns the top-1 class index (or -1).
int {sym}_classify(const float* features, int n) {{
  if (!g_interpreter) return -1;
  TfLiteTensor* in = g_interpreter->input(0);
  const float s = in->params.scale != 0.f ? in->params.scale : 1.f;
  const int zp = in->params.zero_point;
  int count = 0;
  switch (in->type) {{
    case kTfLiteFloat32: count = in->bytes / sizeof(float); break;
    case kTfLiteInt8: case kTfLiteUInt8: count = in->bytes; break;
    default: return -1;
  }}
  for (int i = 0; i < count; ++i) {{
    const float v = i < n ? features[i] : 0.f;
    if (in->type == kTfLiteFloat32) {{ in->data.f[i] = v; continue; }}
    int q = (int)(v / s + (v >= 0 ? 0.5f : -0.5f)) + zp;
    if (in->type == kTfLiteInt8) in->data.int8[i] = (int8_t)(q < -128 ? -128 : q > 127 ? 127 : q);
    else in->data.uint8[i] = (uint8_t)(q < 0 ? 0 : q > 255 ? 255 : q);
  }}
  if (g_interpreter->Invoke() != kTfLiteOk) return -1;
  TfLiteTensor* out = g_interpreter->output(0);
  int classes = out->type == kTfLiteFloat32 ? (int)(out->bytes / sizeof(float)) : (int)out->bytes;
  int best = 0;
  for (int i = 1; i < classes; ++i) {{
    float a = out->type == kTfLiteFloat32 ? out->data.f[i] : out->type == kTfLiteInt8 ? out->data.int8[i] : out->data.uint8[i];
    float b = out->type == kTfLiteFloat32 ? out->data.f[best] : out->type == kTfLiteInt8 ? out->data.int8[best] : out->data.uint8[best];
    if (a > b) best = i;
  }}
  return best;
}}
"""


def _inference_source(name: str, sym: str, header: str, model_bytes: bytes) -> str:
    arena_kb = max(16, min(512, (len(model_bytes) // 1024) // 2 + 32))
    resolver, missing = op_resolver_source(model_bytes)
    if missing:
        raise ValueError(
            f"model uses operators TensorFlow Lite Micro does not implement: {', '.join(missing)}"
        )
    ops = ", ".join(tflite_operators(model_bytes)) or "none"
    return _INFERENCE_CPP.format(name=name, sym=sym, header=header, arena=arena_kb,
                                 resolver=resolver, ops=ops)


def build_arduino_library(model: Path, labels: list[str], dest: Path, name: str) -> Path:
    """Arduino library (.zip, "Sketch → Include Library → Add .ZIP Library")."""
    lib = c_identifier(name)
    root = Path(dest) / lib
    src = root / "src"
    write_c_model(model.read_bytes(), src, symbol=f"{lib}_model", labels=labels, ext="cpp", basename=f"{lib}_model_data")
    sym = c_identifier(f"{lib}_model")
    (src / f"{lib}_inference.cpp").write_text(
        _inference_source(lib, sym, f"{lib}_model_data.h", model.read_bytes()), encoding="utf-8"
    )
    (src / f"{lib}.h").write_text(
        f'#pragma once\n#include <stdint.h>\n#include "{lib}_model_data.h"\n'
        f"int {sym}_setup();\nint {sym}_classify(const float* features, int n);\n",
        encoding="utf-8",
    )
    ex = root / "examples" / f"{lib}_classify"
    ex.mkdir(parents=True, exist_ok=True)
    (ex / f"{lib}_classify.ino").write_text(
        f'#include <{lib}.h>\n\nvoid setup() {{\n  Serial.begin(115200);\n'
        f'  if ({sym}_setup() != 0) {{ Serial.println("model setup failed"); while (1) {{}} }}\n'
        f'  Serial.print("labels: "); Serial.println({sym}_num_labels);\n}}\n\n'
        f"void loop() {{\n  // Fill `features` from your sensor pipeline, then:\n"
        f"  static float features[1024] = {{0}};\n"
        f"  int idx = {sym}_classify(features, 1024);\n"
        f'  if (idx >= 0 && idx < {sym}_num_labels) Serial.println({sym}_labels[idx]);\n  delay(1000);\n}}\n',
        encoding="utf-8",
    )
    (root / "library.properties").write_text(
        f"name={lib}\nversion=1.0.0\nauthor=Graphyn\nmaintainer=Graphyn\n"
        f"sentence=TFLite Micro model {name} exported by Graphyn.\n"
        f"paragraph={len(labels)} labels, {model.stat().st_size} byte model.\n"
        "category=Data Processing\nurl=https://graphyn.local\narchitectures=*\n"
        "depends=Chirale_TensorFLowLite\nincludes=" + f"{lib}.h\n",
        encoding="utf-8",
    )
    zpath = Path(dest) / f"{lib}.zip"
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in sorted(root.rglob("*")):
            if f.is_file():
                zf.write(f, f.relative_to(Path(dest)).as_posix())
    return zpath


def build_zephyr_module(model: Path, labels: list[str], dest: Path, name: str) -> Path:
    """Zephyr external module (add to ZEPHYR_EXTRA_MODULES / west manifest)."""
    mod = c_identifier(name)
    root = Path(dest) / mod
    write_c_model(model.read_bytes(), root / "src", symbol=f"{mod}_model", labels=labels,
                  header_dir=root / "include", basename=f"{mod}_model_data")
    kconf = f"GRAPHYN_{mod.upper()}"
    zdir = root / "zephyr"
    zdir.mkdir(parents=True, exist_ok=True)
    (zdir / "module.yml").write_text(
        f"name: {mod}\nbuild:\n  cmake: zephyr\n  kconfig: zephyr/Kconfig\n", encoding="utf-8"
    )
    (zdir / "Kconfig").write_text(
        f'config {kconf}\n\tbool "Graphyn model {name}"\n\tdefault y\n\thelp\n'
        f"\t  Embeds the {name} TFLite model ({model.stat().st_size} bytes) and its labels.\n",
        encoding="utf-8",
    )
    (zdir / "CMakeLists.txt").write_text(
        f"if(CONFIG_{kconf})\n  zephyr_library()\n"
        f"  zephyr_library_sources(${{ZEPHYR_CURRENT_MODULE_DIR}}/src/{mod}_model_data.c)\n"
        f"  zephyr_include_directories(${{ZEPHYR_CURRENT_MODULE_DIR}}/include)\nendif()\n",
        encoding="utf-8",
    )
    (root / "README.md").write_text(
        f"# {mod} (Zephyr module)\n\nAdd `-DZEPHYR_EXTRA_MODULES={mod}` (or a west project entry), "
        f"enable `CONFIG_{kconf}=y`, and link TFLite Micro (`CONFIG_TENSORFLOW_LITE_MICRO=y`).\n"
        f"Symbols: `{mod}_model`, `{mod}_model_len`, `{mod}_model_labels`.\n",
        encoding="utf-8",
    )
    return root


def build_cmsis_pack(model: Path, labels: list[str], dest: Path, name: str, version: str = "1.0.0") -> Path:
    """CMSIS-Pack (``Graphyn.<Name>.<version>.pack``) with a PDSC component."""
    pack = re.sub(r"[^0-9A-Za-z_-]", "_", name or "Model") or "Model"
    root = Path(dest) / f"Graphyn.{pack}"
    sym = c_identifier(f"{pack}_model")
    write_c_model(model.read_bytes(), root / "Source", symbol=sym, labels=labels,
                  header_dir=root / "Include", basename=f"{pack}_model_data")
    date = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    pdsc = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<package schemaVersion="1.7.7" xmlns:xs="http://www.w3.org/2001/XMLSchema-instance" '
        'xs:noNamespaceSchemaLocation="https://raw.githubusercontent.com/Open-CMSIS-Pack/Open-CMSIS-Pack-Spec/v1.7.7/schema/PACK.xsd">\n'
        "  <vendor>Graphyn</vendor>\n"
        f"  <name>{escape(pack)}</name>\n"
        f"  <description>TFLite Micro model {escape(name)} ({len(labels)} labels) exported by Graphyn.</description>\n"
        "  <url></url>\n"
        f'  <releases>\n    <release version="{escape(version)}" date="{date}">Generated by Graphyn.</release>\n  </releases>\n'
        "  <keywords>\n    <keyword>TensorFlow Lite Micro</keyword>\n  </keywords>\n"
        "  <components>\n"
        f'    <component Cclass="Machine Learning" Cgroup="Model" Csub="{escape(pack)}" Cversion="{escape(version)}">\n'
        f"      <description>Model data and labels for {escape(name)}</description>\n"
        "      <files>\n"
        '        <file category="include" name="Include/"/>\n'
        f'        <file category="header" name="Include/{escape(pack)}_model_data.h"/>\n'
        f'        <file category="source" name="Source/{escape(pack)}_model_data.c"/>\n'
        "      </files>\n    </component>\n  </components>\n</package>\n"
    )
    (root / f"Graphyn.{pack}.pdsc").write_text(pdsc, encoding="utf-8")
    out = Path(dest) / f"Graphyn.{pack}.{version}.pack"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in sorted(root.rglob("*")):
            if f.is_file():
                zf.write(f, f.relative_to(root).as_posix())
    return out


