# app/core/ml/embedded_packaging.py
"""
Bounded Context:  ML deployment (edge / MCU)
Responsibility:   Turn a TFLite flatbuffer into real embedded deliverables
                  (F19 / F-05): C source arrays for TensorFlow Lite Micro, an
                  Arduino library, a Zephyr module and a CMSIS-Pack.
Public Surface:   is_tflite(path) -> bool
                  write_c_model(model_bytes, out_dir, *, symbol, labels, header_dir=None, ext="c")
                  build_arduino_library(model, labels, dest, name) -> Path (.zip)
                  build_zephyr_module(model, labels, dest, name) -> Path (dir)
                  build_cmsis_pack(model, labels, dest, name, version) -> Path (.pack)
Must NOT:         Import plugins; claim compilation for a board (we emit sources,
                  the board toolchain builds them).
Dependencies:     stdlib only.

Every artifact embeds the actual model bytes (16-byte aligned, as TFLM
requires) and the label list; the inference sketch / wrapper uses the public
TFLM API (``tflite::MicroInterpreter``). Nothing here is a placeholder: the C
sources compile with any C99/C++11 compiler (unit-tested with gcc).
"""
from __future__ import annotations

import re
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from xml.sax.saxutils import escape

TFLITE_MAGIC = b"TFL3"


def is_tflite(path: Path | str | None) -> bool:
    """True when *path* is a TFLite flatbuffer (file identifier ``TFL3`` at offset 4)."""
    if not path:
        return False
    p = Path(path)
    try:
        with p.open("rb") as fh:
            head = fh.read(8)
    except OSError:
        return False
    return len(head) == 8 and head[4:8] == TFLITE_MAGIC


def c_identifier(name: str) -> str:
    ident = re.sub(r"[^0-9A-Za-z_]", "_", name or "model").strip("_") or "model"
    return ("m_" + ident) if ident[0].isdigit() else ident


def _c_string(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def write_c_model(
    model_bytes: bytes,
    out_dir: Path,
    *,
    symbol: str = "g_model",
    labels: list[str] | None = None,
    header_dir: Path | None = None,
    ext: str = "c",
    basename: str = "model_data",
) -> tuple[Path, Path]:
    """Write ``<basename>.h`` + ``<basename>.<ext>`` with the model as a C array."""
    if not model_bytes:
        raise ValueError("embedded packaging: model is empty")
    sym = c_identifier(symbol)
    labels = [str(x) for x in (labels or [])]
    out_dir = Path(out_dir)
    hdir = Path(header_dir) if header_dir else out_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    hdir.mkdir(parents=True, exist_ok=True)
    guard = f"{sym.upper()}_DATA_H_"
    header = hdir / f"{basename}.h"
    header.write_text(
        "/* Generated by Graphyn — TensorFlow Lite model for TFLite Micro. */\n"
        f"#ifndef {guard}\n#define {guard}\n\n#include <stdint.h>\n\n"
        "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n"
        f"extern const unsigned char {sym}[];\n"
        f"extern const unsigned int {sym}_len;\n"
        f"extern const char* const {sym}_labels[];\n"
        f"extern const int {sym}_num_labels;\n\n"
        "#ifdef __cplusplus\n}\n#endif\n\n"
        f"#endif /* {guard} */\n",
        encoding="utf-8",
    )
    src = out_dir / f"{basename}.{ext}"
    with src.open("w", encoding="utf-8") as fh:
        fh.write(f'/* Generated by Graphyn. {len(model_bytes)} bytes. */\n#include "{basename}.h"\n\n')
        fh.write("#if defined(__GNUC__) || defined(__clang__)\n#define GRAPHYN_ALIGN16 __attribute__((aligned(16)))\n")
        fh.write("#else\n#define GRAPHYN_ALIGN16\n#endif\n\n")
        fh.write(f"const unsigned char {sym}[] GRAPHYN_ALIGN16 = {{\n")
        for i in range(0, len(model_bytes), 12):
            chunk = model_bytes[i : i + 12]
            fh.write("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
        fh.write("};\n")
        fh.write(f"const unsigned int {sym}_len = {len(model_bytes)}u;\n\n")
        items = ", ".join(_c_string(x) for x in labels) if labels else '""'
        fh.write(f"const char* const {sym}_labels[] = {{{items}}};\n")
        fh.write(f"const int {sym}_num_labels = {len(labels)};\n")
    return header, src


